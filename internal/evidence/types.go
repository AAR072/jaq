var (
	hexDigestRE = regexp.MustCompile(`^[0-9a-f]+$`)
	idRE        = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._:-]*$`)
)

func validateDigest(name, value string, length int) error {
	if len(value) != length || !hexDigestRE.MatchString(value) {
		return fmt.Errorf("%s must be %d lowercase hexadecimal characters", name, length)
	}
	return nil
}

func validateHashes(h Hashes) error {
	if err := validateDigest("md5", h.MD5, 32); err != nil {
		return err
	}
	if err := validateDigest("sha1", h.SHA1, 40); err != nil {
		return err
	}
	if err := validateDigest("sha256", h.SHA256, 64); err != nil {
		return err
	}
	return validateDigest("sha512", h.SHA512, 128)
}

// Validate checks an observation and its content-derived ID.
func (o Observation) Validate() error {
	if o.SchemaVersion != ObservationSchemaVersion {
		return fmt.Errorf("observation %q has unsupported schema_version %q", o.ID, o.SchemaVersion)
	}
	if o.ID == "" || !idRE.MatchString(o.ID) {
		return errors.New("observation id is empty or invalid")
	}
	if o.ID != o.ContentID() {
		return fmt.Errorf("observation %q does not have its content-derived id", o.ID)
	}
	if strings.TrimSpace(o.Type) == "" {
		return errors.New("observation type is empty")
	}
	if o.Artifact.Artifact == "" {
		return errors.New("observation artifact_location.artifact is empty")
	}
	if o.Artifact.Offset < 0 || o.Artifact.Length < 0 || o.Artifact.Line < 0 || o.Artifact.Column < 0 {
		return errors.New("observation artifact location contains a negative coordinate")
	}
	if strings.TrimSpace(o.Analyzer.Name) == "" || strings.TrimSpace(o.Analyzer.Version) == "" {
		return errors.New("observation analyzer name and version are required")
	}
	if o.Analyzer.ConfigHash != "" {
		if err := validateDigest("analyzer.config_hash", o.Analyzer.ConfigHash, 64); err != nil {
			return err
		}
	}
	if strings.TrimSpace(o.Provenance.Source) == "" {
		return errors.New("observation provenance.source is required")
	}
	if o.Provenance.InputSHA256 != "" {
		if err := validateDigest("provenance.input_sha256", o.Provenance.InputSHA256, 64); err != nil {
			return err
		}
	}
	seenParents := map[string]struct{}{}
	for _, id := range o.Provenance.ParentObservationIDs {
		if id == "" || !idRE.MatchString(id) {
			return fmt.Errorf("observation provenance contains invalid parent ID %q", id)
		}
		if _, exists := seenParents[id]; exists {
			return fmt.Errorf("observation provenance repeats parent ID %q", id)
		}
		seenParents[id] = struct{}{}
	}
	for field, ids := range map[string][]string{
		"references":              o.References,
		"reference_ids":           o.ReferenceIDs,
		"calls":                   o.Calls,
		"call_targets":            o.CallTargets,
		"callees":                 o.Callees,
		"callers":                 o.Callers,
		"related_observation_ids": o.RelatedObservationIDs,
	} {
		seen := map[string]struct{}{}
		for _, id := range ids {
			if id == "" || !idRE.MatchString(id) {
				return fmt.Errorf("observation %s contains invalid related ID %q", field, id)
			}
			if _, exists := seen[id]; exists {
				return fmt.Errorf("observation %s repeats related ID %q", field, id)
			}
			seen[id] = struct{}{}
		}
	}
	if o.AnalyzerVersion != "" && strings.TrimSpace(o.AnalyzerVersion) == "" {
		return errors.New("observation analyzer_version is empty")
	}
	if err := validateJSONValue("raw_value", o.RawValue); err != nil {
		return err
	}
	if err := validateJSONValue("normalized_value", o.NormalizedValue); err != nil {
		return err
	}
	if err := validateJSONValue("relationships", o.Relationships); err != nil {
		return err
	}
	return validateJSONValue("metadata", o.Metadata)
}

func validateJSONValue(name string, value any) error {
	if value == nil {
		return nil
	}
	if _, err := json.Marshal(value); err != nil {
		return fmt.Errorf("%s is not JSON serializable: %w", name, err)
	}
	return nil
}

// Validate checks a manifest's schema, artifact identity, timestamps, and
// status.  Empty maps are allowed for early-stage manifests.
func (m RunManifest) Validate() error {
	if m.SchemaVersion != ManifestSchemaVersion {
		return fmt.Errorf("manifest has unsupported schema_version %q", m.SchemaVersion)
	}
	if m.RunID == "" || !idRE.MatchString(m.RunID) {
		return errors.New("manifest run_id is empty or invalid")
	}
	if m.Artifact.Size < 0 {
		return errors.New("manifest artifact size is negative")
	}
	if err := validateHashes(m.Artifact.Hashes); err != nil {
		return fmt.Errorf("manifest artifact hashes: %w", err)
	}
	if m.StartedAt.IsZero() {
		return errors.New("manifest started_at is required")
	}
	if !m.FinishedAt.IsZero() && m.FinishedAt.Before(m.StartedAt) {
		return errors.New("manifest finished_at is before started_at")
	}
	switch m.Status {
	case "running", "completed", "failed", "partial":
	default:
		return fmt.Errorf("manifest status %q is invalid", m.Status)
	}
	for role, model := range m.ModelRoles {
		if strings.TrimSpace(role) == "" {
			return errors.New("manifest contains an empty model role")
		}
		if strings.TrimSpace(model.Model) == "" {
			return fmt.Errorf("manifest model role %q has empty model", role)
		}
	}
	for name, hash := range m.ConfigurationHashes {
		if err := validateDigest("configuration hash "+name, hash, 64); err != nil {
			return err
		}
	}
	for name, hash := range m.PromptHashes {
		if err := validateDigest("prompt hash "+name, hash, 64); err != nil {
			return err
		}
	}
	return nil
}

// Validate checks a claim independently of evidence existence.  Use
// ValidateClaims for cross-record evidence reference checks.
func (c Claim) Validate() error {
	if c.SchemaVersion != ClaimSchemaVersion {
		return fmt.Errorf("claim %q has unsupported schema_version %q", c.ID, c.SchemaVersion)
	}
	if c.ID == "" || !idRE.MatchString(c.ID) {
		return errors.New("claim id is empty or invalid")
	}
	if strings.TrimSpace(c.Classification) == "" {
		return fmt.Errorf("claim %q has empty classification", c.ID)
	}
	if strings.TrimSpace(c.Explanation) == "" {
		return fmt.Errorf("claim %q has empty explanation", c.ID)
	}
	if c.AssetRole != nil {
		assetRole, ok := c.AssetRole.(string)
		if !ok || strings.TrimSpace(assetRole) == "" {
			return fmt.Errorf("claim %q asset_role must be a nonempty string or null", c.ID)
		}
	}
	if math.IsNaN(c.Confidence) || math.IsInf(c.Confidence, 0) || c.Confidence < 0 || c.Confidence > 1 {
		return fmt.Errorf("claim %q confidence must be between 0 and 1", c.ID)
	}
	if len(c.EvidenceIDs) == 0 {
		return fmt.Errorf("claim %q must cite evidence", c.ID)
	}
	seen := map[string]struct{}{}
	for _, id := range c.EvidenceIDs {
		if id == "" || !idRE.MatchString(id) {
			return fmt.Errorf("claim %q contains invalid evidence id %q", c.ID, id)
		}
		if _, ok := seen[id]; ok {
			return fmt.Errorf("claim %q repeats evidence id %q", c.ID, id)
		}
		seen[id] = struct{}{}
	}
	if c.Reachability.SchemaVersion != "" && c.Reachability.SchemaVersion != SchemaVersion {
		return fmt.Errorf("claim %q has unsupported reachability schema_version %q", c.ID, c.Reachability.SchemaVersion)
	}
	switch c.Reachability.Status {
	case "reachable", "not_reachable", "unknown":
	default:
		return fmt.Errorf("claim %q has invalid reachability status %q", c.ID, c.Reachability.Status)
	}
	for _, entrypoint := range c.Reachability.Entrypoints {
		if strings.TrimSpace(entrypoint) == "" {
			return fmt.Errorf("claim %q has an empty reachability entrypoint", c.ID)
		}
	}
	seenPathEvidence := map[string]struct{}{}
	for _, evidenceID := range c.Reachability.PathEvidenceIDs {
		if evidenceID == "" || !idRE.MatchString(evidenceID) {
			return fmt.Errorf("claim %q has invalid reachability evidence id %q", c.ID, evidenceID)
		}
		if _, exists := seenPathEvidence[evidenceID]; exists {
			return fmt.Errorf("claim %q repeats reachability evidence %q", c.ID, evidenceID)
		}
		seenPathEvidence[evidenceID] = struct{}{}
	}
	if err := validateJSONValue("claim metadata", c.Metadata); err != nil {
		return err
	}
	return nil
}

// ValidateClaims validates claims and requires every cited evidence ID to be
// present in observations.
func ValidateClaims(claims []Claim, observations []Observation) error {
	evidence := make(map[string]struct{}, len(observations))
	for _, observation := range observations {
		if err := observation.Validate(); err != nil {
			return fmt.Errorf("observation %q: %w", observation.ID, err)
		}
		if _, exists := evidence[observation.ID]; exists {
			return fmt.Errorf("duplicate observation id %q", observation.ID)
		}
		evidence[observation.ID] = struct{}{}
	}
	seenClaims := make(map[string]struct{}, len(claims))
	for _, claim := range claims {
		if err := claim.Validate(); err != nil {
			return err
		}
		if _, exists := seenClaims[claim.ID]; exists {
			return fmt.Errorf("duplicate claim id %q", claim.ID)
		}
		seenClaims[claim.ID] = struct{}{}
		for _, evidenceID := range claim.EvidenceIDs {
			if _, exists := evidence[evidenceID]; !exists {
				return fmt.Errorf("claim %q cites missing evidence %q", claim.ID, evidenceID)
			}
		}
		for _, evidenceID := range claim.Reachability.PathEvidenceIDs {
			if _, exists := evidence[evidenceID]; !exists {
				return fmt.Errorf("claim %q reachability cites missing evidence %q", claim.ID, evidenceID)
			}
		}
	}
	return nil
}

// ValidateJudgment validates a judgment and cross-checks its claim/evidence
// references.  A judge may cite a subset of the investigator's evidence.
func ValidateJudgment(j Judgment, claims []Claim, observations []Observation) error {
	if j.SchemaVersion != JudgmentSchemaVersion {
		return fmt.Errorf("judgment for %q has unsupported schema_version %q", j.ClaimID, j.SchemaVersion)
	}
	if j.ClaimID == "" || !idRE.MatchString(j.ClaimID) {
		return errors.New("judgment claim_id is empty or invalid")
	}
	switch j.Verdict {
	case "supported", "unsupported", "unclear":
	default:
		return fmt.Errorf("judgment verdict %q is invalid", j.Verdict)
	}
	claimIDs := map[string]struct{}{}
	claimEvidence := map[string]map[string]struct{}{}
	for _, c := range claims {
		claimIDs[c.ID] = struct{}{}
		allowed := make(map[string]struct{}, len(c.EvidenceIDs)+len(c.Reachability.PathEvidenceIDs))
		for _, id := range append(append([]string{}, c.EvidenceIDs...), c.Reachability.PathEvidenceIDs...) {
			allowed[id] = struct{}{}
		}
		claimEvidence[c.ID] = allowed
	}
	if _, ok := claimIDs[j.ClaimID]; !ok {
		return fmt.Errorf("judgment cites missing claim %q", j.ClaimID)
	}
	evidenceIDs := map[string]struct{}{}
	for _, o := range observations {
		evidenceIDs[o.ID] = struct{}{}
	}
	seen := map[string]struct{}{}
	for _, id := range j.CitedEvidenceIDs {
		if _, ok := evidenceIDs[id]; !ok {
			return fmt.Errorf("judgment for %q cites missing evidence %q", j.ClaimID, id)
		}
		if _, ok := seen[id]; ok {
			return fmt.Errorf("judgment for %q repeats evidence %q", j.ClaimID, id)
		}
		if _, ok := claimEvidence[j.ClaimID][id]; !ok {
			return fmt.Errorf("judgment for %q cites evidence outside the claim", j.ClaimID)
		}
		seen[id] = struct{}{}
	}
	if strings.TrimSpace(j.JudgeModel) == "" || strings.TrimSpace(j.Explanation) == "" {
		return fmt.Errorf("judgment for %q requires judge_model and explanation", j.ClaimID)
	}
	for _, key := range []string{"provider", "model"} {
		value, ok := j.ModelMetadata[key].(string)
		if !ok || strings.TrimSpace(value) == "" {
			return fmt.Errorf("judgment for %q has incomplete model_metadata", j.ClaimID)
		}
	}
	if err := validateJSONValue("judgment model_metadata", j.ModelMetadata); err != nil {
		return err
	}
	if err := validateJSONValue("judgment usage", j.Usage); err != nil {
		return err
	}
	return nil
}

// ValidateVerificationResult checks one deterministic verifier result.
func ValidateVerificationResult(v ClaimVerification) error {
	if v.SchemaVersion != ScoreSchemaVersion {
		return fmt.Errorf("verification result for %q has unsupported schema_version %q", v.ClaimID, v.SchemaVersion)
	}
	if v.ClaimID == "" || !idRE.MatchString(v.ClaimID) {
		return errors.New("verification result claim_id is empty or invalid")
	}
	switch v.Status {
	case "accepted", "rejected", "unclear":
	default:
		return fmt.Errorf("verification result for %q has invalid status %q", v.ClaimID, v.Status)
	}
	if v.Accepted != (v.Status == "accepted") {
		return fmt.Errorf("verification result for %q has inconsistent accepted/status", v.ClaimID)
	}
	for _, reason := range v.Reasons {
		if strings.TrimSpace(reason) == "" {
			return fmt.Errorf("verification result for %q has empty reason", v.ClaimID)
		}
	}
	seen := map[string]struct{}{}
	for _, id := range v.EvidenceIDs {
		if id == "" || !idRE.MatchString(id) {
			return fmt.Errorf("verification result for %q has invalid evidence id %q", v.ClaimID, id)
		}
		if _, ok := seen[id]; ok {
			return fmt.Errorf("verification result for %q repeats evidence %q", v.ClaimID, id)
		}
		seen[id] = struct{}{}
	}
	if v.Confidence != nil && (math.IsNaN(*v.Confidence) || math.IsInf(*v.Confidence, 0) || *v.Confidence < 0 || *v.Confidence > 1) {
		return fmt.Errorf("verification result for %q confidence must be between 0 and 1", v.ClaimID)
	}
	return nil
}

// ValidateScore validates score records and all optional judgments against the
// provided claims and observations.
func (s Score) Validate(claims []Claim, observations []Observation) error {
	if s.SchemaVersion != ScoreSchemaVersion {
		return fmt.Errorf("score has unsupported schema_version %q", s.SchemaVersion)
	}
	if s.Accepted < 0 || s.Rejected < 0 || s.Unclear < 0 {
		return errors.New("score counts must be nonnegative")
	}
	if math.IsNaN(s.Confidence) || math.IsInf(s.Confidence, 0) || s.Confidence < 0 || s.Confidence > 1 {
		return errors.New("score confidence must be between 0 and 1")
	}
	if err := ValidateClaims(claims, observations); err != nil {
		return err
	}
	claimIDs := make(map[string]struct{}, len(claims))
	claimByID := make(map[string]Claim, len(claims))
	claimEvidence := make(map[string]map[string]struct{}, len(claims))
	for _, c := range claims {
		claimIDs[c.ID] = struct{}{}
		claimByID[c.ID] = c
		claimEvidence[c.ID] = make(map[string]struct{}, len(c.EvidenceIDs))
		for _, id := range c.EvidenceIDs {
			claimEvidence[c.ID][id] = struct{}{}
		}
	}
	if claims != nil && len(s.VerificationResults) != len(claims) {
		return fmt.Errorf("score has %d verification results for %d claims", len(s.VerificationResults), len(claims))
	}
	seenVerification := map[string]struct{}{}
	countAccepted, countRejected, countUnclear := 0, 0, 0
	for _, v := range s.VerificationResults {
		if err := ValidateVerificationResult(v); err != nil {
			return err
		}
		if _, ok := claimIDs[v.ClaimID]; !ok {
			return fmt.Errorf("score verification cites missing claim %q", v.ClaimID)
		}
		if _, ok := seenVerification[v.ClaimID]; ok {
			return fmt.Errorf("score repeats verification for claim %q", v.ClaimID)
		}
		seenVerification[v.ClaimID] = struct{}{}
		switch v.Status {
		case "accepted":
			countAccepted++
		case "rejected":
			countRejected++
		case "unclear":
			countUnclear++
		}
		if evidence, ok := claimEvidence[v.ClaimID]; ok {
			for _, evidenceID := range v.EvidenceIDs {
				if _, exists := evidence[evidenceID]; !exists {
					return fmt.Errorf("verification for claim %q cites evidence outside the claim", v.ClaimID)
				}
			}
		}
		claim := claimByID[v.ClaimID]
		if v.Status == "accepted" && claim.Unresolved {
			return fmt.Errorf("unresolved claim %q cannot be accepted", v.ClaimID)
		}
		if v.Status == "accepted" && claim.Reachability.Status == "reachable" {
			if v.ReachabilitySupported == nil || !*v.ReachabilitySupported {
				return fmt.Errorf("accepted reachable claim %q is not marked reachability-supported", v.ClaimID)
			}
			if !SupportsReachability(claim, observations) {
				return fmt.Errorf("accepted reachable claim %q has no structured evidence path", v.ClaimID)
			}
		}
	}
	if s.Accepted != countAccepted || s.Rejected != countRejected || s.Unclear != countUnclear {
		return fmt.Errorf("score counts do not match verification result statuses")
	}
	seenJudgment := map[string]struct{}{}
	for _, j := range s.Judgments {
		if err := ValidateJudgment(j, claims, observations); err != nil {
			return err
		}
		if _, ok := seenJudgment[j.ClaimID]; ok {
			return fmt.Errorf("score repeats judgment for claim %q", j.ClaimID)
		}
		seenJudgment[j.ClaimID] = struct{}{}
		for _, v := range s.VerificationResults {
			if v.ClaimID != j.ClaimID {
				continue
			}
			if v.Status == "accepted" && j.Verdict != "supported" {
				return fmt.Errorf("accepted verification for claim %q conflicts with judge verdict %q", j.ClaimID, j.Verdict)
			}
		}
	}
	for label, ids := range map[string][]string{
		"accepted": s.AcceptedClaimIDs,
		"rejected": s.RejectedClaimIDs,
		"unclear":  s.UnclearClaimIDs,
	} {
		seen := map[string]struct{}{}
		for _, id := range ids {
			if _, ok := claimIDs[id]; !ok {
				return fmt.Errorf("score %s list cites missing claim %q", label, id)
			}
			if _, ok := seen[id]; ok {
				return fmt.Errorf("score %s list repeats claim %q", label, id)
			}
			seen[id] = struct{}{}
		}
	}
	if err := validateJSONValue("score usage", s.Usage); err != nil {
		return err
	}
	return nil
}

// SupportsReachability independently checks a claim's exact structured graph
// evidence. Free-form values and decompiler text are never parsed as edges.
func SupportsReachability(claim Claim, observations []Observation) bool {
	if claim.Reachability.Status != "reachable" || len(claim.Reachability.Entrypoints) == 0 || len(claim.Reachability.PathEvidenceIDs) == 0 {
		return false
	}
	byID := make(map[string]Observation, len(observations))
	for _, observation := range observations {
		byID[observation.ID] = observation
	}
	path := make(map[string]struct{}, len(claim.Reachability.PathEvidenceIDs))
	allowed := make(map[string]struct{}, len(claim.EvidenceIDs)+len(claim.Reachability.PathEvidenceIDs))
	for _, id := range claim.EvidenceIDs {
		if _, exists := byID[id]; exists {
			allowed[id] = struct{}{}
		}
	}
	for _, id := range claim.Reachability.PathEvidenceIDs {
		if _, exists := byID[id]; !exists {
			return false
		}
		path[id] = struct{}{}
		allowed[id] = struct{}{}
		for _, endpoint := range append(endpointIDs(byID[id], true), endpointIDs(byID[id], false)...) {
			if _, exists := byID[endpoint]; exists {
				allowed[endpoint] = struct{}{}
			}
		}
	}
	starts := make(map[string]struct{})
	for _, entrypoint := range claim.Reachability.Entrypoints {
		if _, exists := byID[entrypoint]; exists {
			starts[entrypoint] = struct{}{}
			allowed[entrypoint] = struct{}{}
			continue
		}
		for _, observation := range observations {
			value, ok := observation.NormalizedValue.(string)
			if ok && value == entrypoint {
				starts[observation.ID] = struct{}{}
				allowed[observation.ID] = struct{}{}
			}
		}
	}
	if len(starts) == 0 {
		return false
	}
	edges := make(map[string][]string)
	for _, observation := range observations {
		for _, target := range append(append(append(append(append(append([]string{}, observation.Calls...), observation.CallTargets...), observation.Callees...), observation.References...), observation.ReferenceIDs...), observation.RelatedObservationIDs...) {
			if _, sourceOK := allowed[observation.ID]; sourceOK {
				if _, targetOK := allowed[target]; targetOK {
					edges[observation.ID] = append(edges[observation.ID], target)
				}
			}
		}
		sources, targets := endpointIDs(observation, true), endpointIDs(observation, false)
		for _, source := range sources {
			for _, target := range targets {
				if _, sourceOK := allowed[source]; sourceOK {
					if _, targetOK := allowed[target]; targetOK && source != target {
						edges[source] = append(edges[source], target)
					}
				}
			}
		}
	}
	pending := make([]string, 0, len(starts))
	visited := make(map[string]struct{}, len(starts))
	for start := range starts {
		pending = append(pending, start)
		visited[start] = struct{}{}
	}
	for len(pending) > 0 {
		current := pending[0]
		pending = pending[1:]
		for _, target := range edges[current] {
			if _, seen := visited[target]; seen {
				continue
			}
			visited[target] = struct{}{}
			pending = append(pending, target)
			if _, isPath := path[target]; isPath {
				return true
			}
		}
	}
	// A path relationship observation can connect a start directly to a cited
	// target even though the relationship record is not itself a graph node.
	cited := claimEvidenceSet(claim)
	for pathID := range path {
		for _, source := range endpointIDs(byID[pathID], true) {
			if _, isStart := starts[source]; !isStart {
				continue
			}
			for _, target := range endpointIDs(byID[pathID], false) {
				if _, isCited := cited[target]; isCited {
					return true
				}
			}
		}
	}
	return false
}

func claimEvidenceSet(claim Claim) map[string]struct{} {
	result := make(map[string]struct{}, len(claim.EvidenceIDs))
	for _, id := range claim.EvidenceIDs {
		result[id] = struct{}{}
	}
	return result
}

func endpointIDs(observation Observation, source bool) []string {
	keys := []string{"target_id", "target", "to", "callee_id", "callee"}
	if source {
		keys = []string{"source_id", "source", "from", "caller_id", "caller"}
	}
	var result []string
	for _, container := range []map[string]any{observation.Relationships, observation.Metadata} {
		for _, key := range keys {
			switch value := container[key].(type) {
			case string:
				if value != "" {
					result = append(result, value)
				}
			case []string:
				result = append(result, value...)
			case []any:
				for _, item := range value {
					if text, ok := item.(string); ok && text != "" {
						result = append(result, text)
					}
				}
			}
		}
	}
	return result
}

// SortObservations returns a copy sorted by content-derived ID and stable
// serialized content.  Sorting makes JSONL packages reproducible.
func SortObservations(observations []Observation) []Observation {
	result := append([]Observation(nil), observations...)
	sort.SliceStable(result, func(i, j int) bool {
		if result[i].ID != result[j].ID {
			return result[i].ID < result[j].ID
		}
		left, _ := json.Marshal(result[i])
		right, _ := json.Marshal(result[j])
		return string(left) < string(right)
	})
	return result
}

// DeduplicateObservations removes exact duplicate observations by ID and
// returns an error if one content ID is used by different content.
func DeduplicateObservations(observations []Observation) ([]Observation, error) {
	sorted := SortObservations(observations)
	result := make([]Observation, 0, len(sorted))
	seen := make(map[string]Observation, len(sorted))
	for _, observation := range sorted {
		if err := observation.Validate(); err != nil {
			return nil, err
		}
		if previous, ok := seen[observation.ID]; ok {
			if previous.ContentID() != observation.ContentID() {
				return nil, fmt.Errorf("observation id %q has conflicting content", observation.ID)
			}
			continue
		}
		seen[observation.ID] = observation
		result = append(result, observation)
	}
	if err := ValidateObservationReferences(result); err != nil {
		return nil, err
	}
	return result, nil
}

// ValidateObservationReferences requires every structured call/reference ID
// to resolve inside the same evidence package. Free-form values are ignored.
func ValidateObservationReferences(observations []Observation) error {
	ids := make(map[string]struct{}, len(observations))
	for _, observation := range observations {
		ids[observation.ID] = struct{}{}
	}
	for _, observation := range observations {
		references := append(append(append(append(append(append([]string{}, observation.Calls...), observation.CallTargets...), observation.Callees...), observation.References...), observation.ReferenceIDs...), observation.RelatedObservationIDs...)
		references = append(references, endpointIDs(observation, true)...)
		references = append(references, endpointIDs(observation, false)...)
		references = append(references, observation.Provenance.ParentObservationIDs...)
		for _, reference := range references {
			if _, exists := ids[reference]; !exists {
				return fmt.Errorf("observation %q cites missing structured relationship %q", observation.ID, reference)
			}
		}
	}
	return nil
}

// SortAndDeduplicateObservations is a convenience wrapper for callers that
// already validated observations.  Invalid input is retained so the caller
// can surface the validation error at the persistence boundary.
func SortAndDeduplicateObservations(observations []Observation) []Observation {
	sorted := SortObservations(observations)
	result := make([]Observation, 0, len(sorted))
	seen := map[string]struct{}{}
	for _, observation := range sorted {
		if _, ok := seen[observation.ID]; ok {
			continue
		}
		seen[observation.ID] = struct{}{}
		result = append(result, observation)
	}
	return result
}
